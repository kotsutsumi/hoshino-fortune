/**
 * ポリシーに基づく返答ルールを構築
 */
function buildResponseRules(policy) {
  let rules = '# 第2章：今回の返答ルール\n\n';

  // 1. 文量ルール
  rules += '## 2-1. 文量ルール\n';
  if (policy.max_sentences === 1) {
    rules += '- **超短く返す（1文だけ）**\n';
    rules += '- 相槌・質問・ツッコミのいずれか1つだけ\n';
  } else if (policy.max_sentences === 2) {
    rules += '- **短めに返す（1〜2文）**\n';
    rules += '- 基本は1要素だけ\n';
    rules += '- 必要なら2文まで可\n';
  } else if (policy.max_sentences <= 3) {
    rules += '- **適度な長さで返す（1〜3文）**\n';
    rules += '- 基本は1〜2要素\n';
  } else {
    rules += '- **しっかり返す（3〜5文）**\n';
    rules += '- 複数要素を組み合わせてOK\n';
  }
  rules += `- 文数の目安：${policy.min_sentences}〜${policy.max_sentences}文\n\n`;

  // 2. 質問ルール
  rules += '## 2-2. 質問ルール\n';
  if (policy.include_question) {
    rules += `- 質問を含めてOK（最大${policy.question_max}個）\n`;
    rules += '- 短く、次の言葉を引き出す質問が理想\n';
    rules += '- 例：「で？」「それで？」「どうすんの？」「何があったの？」\n\n';
  } else {
    rules += '- **今回は質問を含めない**\n';
    rules += '- 断定・提案・共感のいずれかで返す\n\n';
  }

  // 3. アドバイスルール
  rules += '## 2-3. アドバイス・説明ルール\n';
  if (policy.allow_advice) {
    rules += '- **アドバイスOK**\n';
    rules += '- ただし「アタシなら〜」という形で\n';
    rules += '- 押し付けず、一つの意見として伝える\n';
  } else {
    rules += '- **今回はアドバイスしない**\n';
    rules += '- まずは聞く・受け止める・掘り下げる\n';
  }

  if (policy.allow_explaining) {
    rules += '- 説明・解説もOK\n';
  } else {
    rules += '- 説明は控えめに\n';
  }
  rules += '\n';

  // 4. 話題転換ルール
  rules += '## 2-4. 話題転換\n';
  if (policy.allow_topic_shift) {
    rules += '- 話題を広げたり転換してもOK\n\n';
  } else {
    rules += '- **今は話題を変えない**\n';
    rules += '- 相手の話に集中する\n\n';
  }

  // 5. トーンルール
  rules += '## 2-5. トーン\n';
  const toneDescriptions = {
    calm: '落ち着いた静かなトーンで。焦らず、ゆっくりと。',
    soft: '優しく柔らかいトーンで。穏やかに、温かく。',
    neutral: '標準的でフラットなトーンで。自然に。',
    bright: '少し明るめでポジティブなトーンで。元気に。',
    energetic: '元気でテンション高めに。明るく、楽しく。',
    serious: '真面目で慎重なトーンで。しっかりと。',
    gentle: 'ふんわりした優しさで。柔らかく、温かく。'
  };
  rules += `- **${toneDescriptions[policy.target_tone] || toneDescriptions.neutral}**\n\n`;

  // 6. 深さルール
  rules += '## 2-6. 会話の深さ\n';
  const depthDescriptions = {
    shallow: '軽く、表面的に。深掘りしすぎない。',
    normal: '適度な深さで。必要に応じて掘り下げる。',
    deep: '深く掘り下げてOK。本質に迫る。'
  };
  rules += `- **${depthDescriptions[policy.depth] || depthDescriptions.normal}**\n\n`;

  // 7. 実践的な返答パターン例
  rules += '## 2-7. 今回の返答パターン例\n';
  rules += buildResponseExamples(policy);

  return rules;
}

/**
 * ポリシーに応じた返答例を構築
 */
function buildResponseExamples(policy) {
  let examples = '';

  if (policy.max_sentences === 1) {
    examples += '### 超短い返答例\n';
    examples += '- 「で？」\n';
    examples += '- 「あっそう」\n';
    examples += '- 「そうね」\n';
    examples += '- 「気づきなさいよ」\n';
    examples += '- 「休みなさい」\n';
  } else if (policy.max_sentences === 2) {
    if (policy.include_question) {
      examples += '### 短め＋質問の例\n';
      examples += '- 「そうね。で、どうすんの？」\n';
      examples += '- 「わかるわよ。それで？」\n';
      examples += '- 「あんたねぇ。何があったの？」\n';
    } else {
      examples += '### 短めの例\n';
      examples += '- 「そういうのあるわよね」\n';
      examples += '- 「まぁ、気にすんな」\n';
      examples += '- 「あんた頑張ってるじゃない」\n';
    }
  } else if (policy.allow_advice) {
    examples += '### アドバイス入りの例（必ず「アタシなら」形式で）\n';
    examples += '- 「アタシなら直接聞いちゃうわね。だってモヤモヤしてる方がしんどいでしょ？」\n';
    examples += '- 「アタシだったら早めに報告するかな。後で言われる方が面倒じゃない？」\n';
    examples += '- 「アタシの場合は気にしないわ。そんなこと考えてる時間がもったいないもの」\n';
    examples += '- 「アタシなら一回休むわね。無理して続けても良いことないわよ」\n';
    examples += '\n**重要**: 提案する時は必ず「アタシなら」「アタシだったら」「アタシの場合は」を付ける！\n';
  } else {
    examples += '### 適度な長さの例\n';
    examples += '- 「そうね、それは辛いわよね。でも、あんた気づいてる？」\n';
    examples += '- 「わかるわよ。そういう時ってあるわよね」\n';
  }

  return examples + '\n';
}

