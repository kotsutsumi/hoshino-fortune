/**
 * 年月日から干支を計算する（簡易版）
 */
function calculateGanzhi(year, month, day) {
  // 1900年1月1日を基準とした日数計算
  const baseDate = new Date(1900, 0, 1);
  const targetDate = new Date(year, month - 1, day);
  const daysDiff = Math.floor((targetDate - baseDate) / (1000 * 60 * 60 * 24));
  
  // 60干支の周期で計算
  return GANZHI_LIST[daysDiff % 60];
}

/**
 * 干支から天干を抽出
 */
function extractHeavenlyStem(ganzhi) {
  return ganzhi.charAt(0);
}

/**
 * 十神を判定する（シンプル版）
 */
function determineTenGods(birthDayGanzhi, targetDayGanzhi) {
  // 天干を抽出
  const birthHeavenly = extractHeavenlyStem(birthDayGanzhi);
  const targetHeavenly = extractHeavenlyStem(targetDayGanzhi);
  
  // 事前定義されたマトリクスから十神を取得
  const tenGod = TEN_GODS_COMBINATIONS[birthHeavenly]?.[targetHeavenly];
  
  if (!tenGod) {
    throw new Error(`十神の組み合わせが見つかりません: ${birthHeavenly} → ${targetHeavenly}`);
  }
  
  return {
    birthDayGanzhi,
    targetDayGanzhi,
    birthHeavenly,
    targetHeavenly,
    tenGod,
    description: getTenGodDescription(tenGod)
  };
}

