/**
 * 日付から干支を計算
 */
export function calculateDayGanzhi(date: Date): string {
  const baseDate = new Date(1900, 0, 1);
  const daysDiff = Math.floor((date.getTime() - baseDate.getTime()) / (1000 * 60 * 60 * 24));
  return GANZHI_LIST[((daysDiff % 60) + 60) % 60];
}

/**
 * 干支から天干を抽出
 */
export function extractHeavenlyStem(ganzhi: string): HeavenlyStem {
  return ganzhi.charAt(0) as HeavenlyStem;
}

/**
 * 十神を判定
 */
export function determineTenGod(
  userHeavenlyStem: HeavenlyStem,
  dayHeavenlyStem: HeavenlyStem
): TenGod {
  return TEN_GODS_MATRIX[userHeavenlyStem][dayHeavenlyStem];
}

/**
 * 十神の説明を取得
 */
export function getTenGodDescription(tenGod: TenGod): string {
  return TEN_GOD_DESCRIPTIONS[tenGod];
}

/**
 * 指定日の天干を取得
 */
export function getDayHeavenlyStem(date: Date): HeavenlyStem {
  const ganzhi = calculateDayGanzhi(date);
  return extractHeavenlyStem(ganzhi);
}
